import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const base='https://celebrations-exit-staging.rondes.workers.dev';
const browser=await chromium.launch();
const widths=[360,390,768,1366];
const checkWidth=async(page,label)=>{
 const s=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,body:document.body.scrollWidth,inner:window.innerWidth}));
 assert.ok(s.scroll<=s.inner+1,'Horizontal page overflow on '+label+': '+JSON.stringify(s));
};
try{
 for(const width of widths){
  const mobile=width<600;
  const context=await browser.newContext({viewport:{width,height:mobile?780:840},isMobile:mobile,hasTouch:mobile});
  const page=await context.newPage();page.setDefaultTimeout(15000);
  const jsErrors=[];
  page.on('pageerror',err=>jsErrors.push(String(err)));
  const response=await page.goto(base+'/__editor/demo-preparation');
  assert.equal(response.status(),200);
  await page.locator('#workspace .list .item').first().waitFor();
  assert.equal(await page.locator('#workspace .list .item').count(),9);
  await checkWidth(page,'editor '+width);
  // Five palettes with five shades; change one without affecting text colours.
  await page.locator('#theme-toggle').click();
  assert.equal(await page.locator('#theme-grid .theme-option').count(),5);
  assert.equal(await page.locator('#theme-grid .theme-option .theme-swatch').count(),25);
  const palette=page.locator('#theme-grid .theme-option[data-palette="3"]');
  const paletteName=await palette.locator('strong').innerText();
  await palette.click();
  const chosenFrame=await page.locator('.stage-editor').evaluate(e=>e.style.getPropertyValue('--frame-color'));
  assert.match(chosenFrame,/^#[0-9a-f]{6}$/i);
  assert.equal(await page.locator('.stage-editor .main').evaluate(e=>getComputedStyle(e).backgroundColor),'rgb(255, 255, 255)','Editor backgrounds remain neutral');
  assert.equal(await page.locator('.stage-editor .heading').first().evaluate(e=>getComputedStyle(e).color),'rgb(41, 46, 50)');
  assert.equal(await page.locator('#save-btn').innerText(),'Enregistrer','Palette should autosave locally');
  await page.locator('#workspace .list .item').filter({hasText:'Mercredi'}).click();
  assert.equal((await page.locator('.editor-head h2').innerText()).trim(),'Mercredi','Changing colour must not block day navigation');
  const marker='VISUAL-CHANGE-MERCREDI-'+width;
  await page.locator('#workspace .block .ed').first().fill(marker);
  await page.locator('#save-btn').click();
  await page.reload();
  await page.locator('#workspace .list .item').filter({hasText:'Mercredi'}).click();
  const savedState=await page.evaluate(()=>JSON.parse(localStorage.getItem('celebrations-demo-preparation-'+window.__PREPARATION_SEED__.celebrationId)||'null'));
  const savedPage=savedState?.pages?.find(x=>x.id.startsWith('mercredi-'));
  assert.equal(savedPage?.blocks?.[0]?.text,marker,'Saving the theme must retain the page text after reload');
  await page.locator('#theme-toggle').click();
  assert.equal(await page.locator('#theme-grid .theme-option[data-palette="3"]').getAttribute('aria-pressed'),'true');
  await page.locator('#theme-toggle').click();
  const link=page.locator('#view-site-btn');
  await link.waitFor();
  assert.match(await link.getAttribute('href'),/page=mercredi/);
  const [trial]=await Promise.all([page.waitForEvent('popup'),link.click()]);
  await trial.waitForLoadState('domcontentloaded');
  assert.match(trial.url(),/\/__editor\/voir-le-site/);
  const trialState=await trial.evaluate(()=>({key:'celebrations-demo-preparation-'+window.__TRIAL_SITE_SEED__.celebrationId,storage:localStorage.getItem('celebrations-demo-preparation-'+window.__TRIAL_SITE_SEED__.celebrationId),stage:document.querySelector('#page-heading')?.textContent,html:document.querySelector('#stage-main')?.innerText?.slice(0,400)}));
  assert.ok(trialState.storage?.includes(marker),'Preview must access saved draft on same origin '+JSON.stringify({stage:trialState.stage,html:trialState.html,key:trialState.key}));
  await trial.getByText(marker).waitFor();
  assert.equal(await trial.locator('#palette-label').innerText(),paletteName);
  assert.equal(await trial.evaluate(()=>document.documentElement.style.getPropertyValue('--frame-color')),chosenFrame);
  assert.equal(await trial.locator('body').evaluate(e=>getComputedStyle(e).backgroundColor),'rgb(255, 255, 255)','Trial site backgrounds remain neutral');
  assert.equal(await trial.locator('#page-heading').evaluate(e=>getComputedStyle(e).color),'rgb(41, 46, 50)');
  assert.equal(await trial.locator('.stage-tab').count(),8);
  assert.ok(await trial.locator('#site-paper').evaluate(e=>getComputedStyle(e).borderTopColor)!=='rgb(216, 218, 222)');
  assert.equal(await trial.locator('#page-heading').innerText(),'Mercredi');
  await checkWidth(trial,'trial site '+width);
  await trial.getByRole('button',{name:'Dimanche'}).click();
  assert.equal(await trial.locator('#page-heading').innerText(),'Dimanche');
  assert.match(await trial.locator('#back-admin').getAttribute('href'),/page=dimanche/);
  await trial.locator('#menu-toggle').click();
  assert.equal(await trial.locator('.general-tab').count(),1);
  await trial.getByRole('button',{name:'Accueil général'}).click();
  assert.equal(await trial.locator('#page-heading').innerText(),'Accueil général');
  assert.ok(await trial.locator('body').evaluate(e=>e.classList.contains('is-neutral-preview')));
  assert.equal(await trial.locator('#stage-navigation').isVisible(),false);
  await trial.locator('#return-celebration').click();
  assert.equal(await trial.locator('#page-heading').innerText(),'Accueil de la célébration');
  assert.deepEqual(jsErrors,[]);
  console.log('EDITOR_TRIAL_SITE_PASS width='+width+' page_changes_visible=true pages=9 palettes=5 monochrome=true text_dark=true no_horizontal_scroll=true local_storage=true');
  await trial.close();await context.close();
 }
}finally{await browser.close();}
