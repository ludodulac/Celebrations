import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const base='https://celebrations-exit-staging.rondes.workers.dev';
const browser=await chromium.launch();
const widths=[360,390,768,1366];
const checkWidth=async(page,label)=>{
 const s=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,body:document.body.scrollWidth,inner:window.innerWidth}));
 assert.ok(s.scroll<=s.inner+1,'Horizontal page overflow on '+label+': '+JSON.stringify(s));
};
try{
 for(const width of widths){
  const mobile=width<600;
  const context=await browser.newContext({viewport:{width,height:mobile?780:840},isMobile:mobile,hasTouch:mobile});
  const page=await context.newPage();page.setDefaultTimeout(15000);
  const jsErrors=[];
  page.on('pageerror',err=>jsErrors.push(String(err)));
  const response=await page.goto(base+'/__editor/demo-preparation',{waitUntil:'domcontentloaded',timeout:30000});
  assert.equal(response.status(),200);
  await page.locator('#workspace .list .item').first().waitFor();
  assert.equal(await page.locator('#workspace .list .item').count(),9);
  await checkWidth(page,'editor '+width);
  // No manual palette control. Michaël keeps its fixed border colour.
  assert.equal(await page.locator('#theme-toggle, #theme-grid, #theme-picker').count(),0);
  const chosenFrame=await page.locator('.stage-editor').evaluate(e=>e.style.getPropertyValue('--frame-color'));
  assert.match(chosenFrame,/^#[0-9a-f]{6}$/i);
  assert.equal(await page.locator('.stage-editor .main').evaluate(e=>getComputedStyle(e).backgroundColor),'rgb(255, 255, 255)');
  assert.equal(await page.locator('#save-btn').innerText(),'Enregistrer');
  await page.locator('#workspace .list .item').filter({hasText:'Mercredi'}).click();
  assert.ok((await page.locator('#workspace .list .item.active').innerText()).includes('Mercredi'));
  assert.equal(await page.locator('.editor-head h2').count(),0,'No fixed page title in editor');
  const marker='VISUAL-CHANGE-MERCREDI-'+width;
  await page.locator('#workspace .block .ed').first().fill(marker);
  await page.locator('#save-btn').click();
  await page.reload();
  await page.locator('#workspace .list .item').filter({hasText:'Mercredi'}).click();
  const savedState=await page.evaluate(()=>JSON.parse(localStorage.getItem('celebrations-demo-preparation-'+window.__PREPARATION_SEED__.celebrationId)||'null'));
  const savedPage=savedState?.pages?.find(x=>x.id.startsWith('mercredi-'));
  assert.ok(savedPage?.blocks?.some(x=>x.text===marker),'The edit survives reload');
  assert.equal(await page.locator('#theme-toggle').count(),0);
  const link=page.locator('#view-site-btn');
  await link.waitFor();
  assert.match(await link.getAttribute('href'),/page=mercredi/);
  const [trial]=await Promise.all([page.waitForEvent('popup'),link.click()]);
  await trial.waitForLoadState('domcontentloaded');
  assert.match(trial.url(),/\/__editor\/voir-le-site/);
  const trialState=await trial.evaluate(()=>({key:'celebrations-demo-preparation-'+window.__TRIAL_SITE_SEED__.celebrationId,storage:localStorage.getItem('celebrations-demo-preparation-'+window.__TRIAL_SITE_SEED__.celebrationId),stage:document.querySelector('.stage-tab.current')?.textContent,html:document.querySelector('#stage-main')?.innerText?.slice(0,400)}));
  assert.ok(trialState.storage?.includes(marker),'Preview must access saved draft on same origin '+JSON.stringify({stage:trialState.stage,html:trialState.html,key:trialState.key}));
  await trial.getByText(marker).waitFor();
  assert.equal(await trial.locator('#palette-label').count(),0,'No explanatory colour text in reader view');
  assert.equal(await trial.evaluate(()=>document.documentElement.style.getPropertyValue('--frame-color')),chosenFrame);
  assert.equal(await trial.locator('body').evaluate(e=>getComputedStyle(e).backgroundColor),'rgb(255, 255, 255)','Trial site backgrounds remain neutral');
  assert.equal(await trial.locator('#page-heading, #site-hero-title').count(),0,'No uneditable titles in site preview');
  assert.equal(await trial.locator('.stage-tab').count(),8);
  assert.ok(await trial.locator('#site-paper').evaluate(e=>getComputedStyle(e).borderTopColor)!=='rgb(216, 218, 222)');
  assert.equal((await trial.locator('.stage-tab.current').innerText()).trim(),'Mercredi');
  await checkWidth(trial,'trial site '+width);
  await trial.getByRole('button',{name:'Dimanche'}).click();
  assert.equal((await trial.locator('.stage-tab.current').innerText()).trim(),'Dimanche');
  assert.match(await trial.locator('#back-admin').getAttribute('href'),/page=dimanche/);
  await trial.locator('#menu-toggle').click();
  assert.equal(await trial.locator('.general-tab').count(),2);
  await trial.getByRole('button',{name:'⌂ Accueil'}).click();
  assert.equal((await trial.locator('.general-tab.current').innerText()).trim(),'⌂ Accueil');
  assert.ok(await trial.locator('body').evaluate(e=>e.classList.contains('is-neutral-preview')));
  assert.equal(await trial.locator('#stage-navigation').isVisible(),false);
  await trial.goto(base+'/__editor/voir-le-site?celebration=101&page=accueil-celebration',{waitUntil:'domcontentloaded',timeout:30000});
  assert.equal((await trial.locator('.stage-tab.current').innerText()).trim(),'Accueil de la célébration');
  assert.deepEqual(jsErrors,[]);
  console.log('EDITOR_TRIAL_SITE_PASS width='+width+' page_changes_visible=true pages=9 fixed_archangel_colour=true monochrome=true text_dark=true no_horizontal_scroll=true local_storage=true');
  await trial.close();
  // A paragraph has a global font size, but individual words may be bold or coloured.
  await page.locator('#workspace .list .item').filter({hasText:'Mercredi'}).click();
  await page.getByRole('button',{name:'Paragraphe'}).click();
  const inlineBlock=page.locator('#workspace .block').last();
  const inlineText=inlineBlock.locator('.ed.text');
  await inlineText.fill('Début important fin');
  await inlineText.evaluate(z=>{
   const t=z.firstChild,offset=t.textContent.indexOf('important');
   const r=document.createRange();r.setStart(t,offset);r.setEnd(t,offset+'important'.length);
   const s=window.getSelection();s.removeAllRanges();s.addRange(r);
  });
  await inlineBlock.getByLabel('Gras (sélection ou bloc)').click();
  assert.equal(await inlineText.locator('strong').innerText(),'important');
  await inlineText.evaluate(z=>{
   const t=z.firstChild,offset=t.textContent.indexOf('Début');
   const r=document.createRange();r.setStart(t,offset);r.setEnd(t,offset+'Début'.length);
   const s=window.getSelection();s.removeAllRanges();s.addRange(r);
  });
  await inlineBlock.getByLabel('Couleur du texte').fill('#e3342f');
  assert.equal(await inlineText.locator('span').first().innerText(),'Début','Only the selected text gets a coloured span');
  assert.equal(await inlineText.locator('span').first().evaluate(e=>getComputedStyle(e).color),'rgb(227, 52, 47)');
  await inlineBlock.getByLabel('Taille du texte').selectOption('20');
  assert.equal(await inlineText.evaluate(e=>getComputedStyle(e).fontSize),'20px','Font size applies to the paragraph');
  assert.equal(await inlineText.locator('strong').evaluate(e=>getComputedStyle(e).fontSize),'20px','Bold words inherit the global size');
  await page.locator('#save-btn').click();
  await page.reload();
  await page.locator('#workspace .list .item').filter({hasText:'Mercredi'}).click();
  const savedInline=page.locator('.ed.text').filter({hasText:'Début important fin'});
  assert.equal(await savedInline.locator('strong').innerText(),'important','Saved partial bold must survive reload');
  assert.equal(await savedInline.locator('span').first().evaluate(e=>getComputedStyle(e).color),'rgb(227, 52, 47)','Saved partial colour must survive reload');
  const [colourPreview]=await Promise.all([page.waitForEvent('popup'),page.locator('#view-site-btn').click()]);
  const publishedSample=colourPreview.locator('.trial-paragraph').filter({hasText:'Début important fin'});
  await publishedSample.waitFor();
  assert.equal(await publishedSample.locator('strong').innerText(),'important');
  assert.equal(await publishedSample.locator('span').first().evaluate(e=>getComputedStyle(e).color),'rgb(227, 52, 47)');
  assert.equal(await publishedSample.evaluate(e=>getComputedStyle(e).fontSize),'20px');
  assert.notEqual(await publishedSample.locator('strong').evaluate(e=>getComputedStyle(e).color),'rgb(227, 52, 47)','Unselected words should not inherit the selected colour');
  console.log('EDITOR_INLINE_FORMAT_PASS width='+width+' bold_fragment=true color_fragment=true font_size_global=true saved=true site_preview=true');
  await colourPreview.close();
  await context.close();
 }
}finally{await browser.close();}
