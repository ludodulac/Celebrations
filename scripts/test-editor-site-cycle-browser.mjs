import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const base='https://celebrations-exit-staging.rondes.workers.dev';
const browser=await chromium.launch();
try{
 for(const width of [390,1280]){
  const ctx=await browser.newContext({viewport:{width,height:850},isMobile:width===390,hasTouch:width===390});
  const page=await ctx.newPage();page.setDefaultTimeout(18000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'/__editor/demo');
  assert.ok(page.url().endsWith('/__editor/demo-preparation'),'The old design must redirect to the new editor');
  await page.goto(base+'/__editor/demo-preparation?celebration=101',{waitUntil:'domcontentloaded',timeout:30000});
  await page.locator('#workspace .list .item').first().waitFor();
  const publicAudio=await page.evaluate(()=>window.__PREPARATION_SEED__?.media?.map(x=>x.name)||[]);
  console.log('SITE_HISTORICAL_AUDIO_CATALOGUE count='+publicAudio.length+' examples='+publicAudio.slice(0,4).join(', '));
  assert.equal(await page.locator('#workspace .list .item').count(),9);
  assert.ok((await page.locator('#workspace .list .item.active').innerText()).includes('Accueil de la célébration'));
  // Existing Michaël celebration: one Wednesday controls five consecutive days.
  await page.getByLabel('Mercredi de la célébration').fill('2026-11-04');
  await page.locator('#workspace .list .item').filter({hasText:'Vendredi'}).click();
  assert.equal((await page.locator('[data-role="celebration-date"]').innerText()).trim(),'6 novembre 2026');
  await page.locator('#workspace .list .item').filter({hasText:'Dimanche'}).click();
  assert.equal((await page.locator('[data-role="celebration-date"]').innerText()).trim(),'8 novembre 2026');
  // Preparation can have several distinct dates, not merely a fixed start/end range.
  await page.locator('#workspace .list .item').filter({hasText:'Préparation',exact:true}).first().click();
  await page.getByLabel('Date de préparation 1',{exact:true}).fill('2026-10-21');
  await page.getByRole('button',{name:'＋ Date'}).click();
  await page.getByLabel('Date de préparation 2',{exact:true}).fill('2026-10-28');
  assert.equal((await page.locator('[data-role="celebration-date"]').innerText()).trim(),'21 octobre 2026 · 28 octobre 2026');
  await page.reload();
  await page.locator('#workspace .list .item').filter({hasText:'Préparation',exact:true}).first().click();
  assert.equal(await page.getByLabel('Date de préparation 1',{exact:true}).inputValue(),'2026-10-21');
  assert.equal(await page.getByLabel('Date de préparation 2',{exact:true}).inputValue(),'2026-10-28');
  const [datedSite]=await Promise.all([page.waitForEvent('popup'),page.locator('#view-site-btn').click()]);
  assert.equal((await datedSite.locator('[data-role="celebration-date"]').innerText()).trim(),'21 octobre 2026 · 28 octobre 2026');
  await datedSite.getByRole('button',{name:'Mercredi',exact:false}).click();
  assert.equal((await datedSite.locator('[data-role="celebration-date"]').innerText()).trim(),'4 novembre 2026');
  await datedSite.close();
  await page.locator('[data-tab="celebrations"]').click();
  await page.getByText('Nouvelle célébration : Gabriel').waitFor();
  await page.getByLabel('Date du mercredi').fill('2026-11-04');
  await page.getByRole('button',{name:'Créer Gabriel'}).click();
  await page.waitForURL('**/demo-preparation?celebration=plan-gabriel-2026-11-04');
  assert.ok((await page.locator('#workspace .list .item.active').innerText()).includes('Accueil de la célébration'));
  assert.equal(await page.locator('#workspace .list .item').count(),9);
  await page.locator('#workspace .list .item').filter({hasText:'Dimanche'}).click();
  assert.equal((await page.locator('[data-role="celebration-date"]').innerText()).trim(),'8 novembre 2026');
  await page.getByLabel('Mercredi de la célébration').fill('2026-12-30');
  assert.equal((await page.locator('[data-role="celebration-date"]').innerText()).trim(),'3 janvier 2027');
  await page.reload();
  await page.locator('#workspace .list .item').filter({hasText:'Dimanche'}).click();
  assert.equal((await page.locator('[data-role="celebration-date"]').innerText()).trim(),'3 janvier 2027');
  const [preview]=await Promise.all([page.waitForEvent('popup'),page.locator('#view-site-btn').click()]);
  await preview.locator('.stage-tab.current').getByText('Dimanche').waitFor();
  await preview.locator('#menu-toggle').click();
  await preview.getByRole('button',{name:'✧ Célébrations'}).click();
  await preview.locator('.celebration-choices').waitFor();
  assert.ok(await preview.locator('.celebration-choice').count()>=2);
  await preview.locator('#menu-toggle').click();
  await preview.getByRole('button',{name:'⌂ Accueil'}).click();
  assert.equal((await preview.locator('.general-tab.current').textContent()).trim(),'⌂ Accueil','Home remains selected when the hamburger closes');
  assert.ok(await preview.locator('body').evaluate(e=>e.classList.contains('is-neutral-preview')));
  assert.equal(await preview.locator('.footer a').innerText(),'Administration');
  assert.equal(await preview.locator('header a').count(),0,'No administration link in top of public preview');
  const back=await preview.locator('#back-admin').getAttribute('href');
  assert.ok(back.includes('page=neutral-accueil-general'));
  await preview.locator('#back-admin').click();
  await page.locator('[data-tab="audio"]').click();
  await page.locator('[data-action="back-to-editor"]').click();
  await page.locator('#workspace .list .item.active').waitFor();
  // Reuse one of the MP3 files already present in the historical public site.
  await page.goto(base+'/__editor/demo-preparation?celebration=101&page=mercredi',{waitUntil:'domcontentloaded',timeout:30000});
  await page.locator('#workspace .list .item').filter({hasText:'Mercredi'}).click();
  const before=await page.locator('.audio-block audio').count();
  await page.locator('[data-tab="audio"]').click();
  const historic=page.locator('[data-action="use-historical-mp3"]').first();
  await historic.waitFor();
  await historic.click();
  assert.equal(await page.locator('.audio-block audio').count(),before+1);
  const source=await page.locator('.audio-block audio').last().getAttribute('src');
  assert.match(source,/^\/media\/.+\.mp3$/i);
  await page.locator('#save-btn').click();
  const [audioSite]=await Promise.all([page.waitForEvent('popup'),page.locator('#view-site-btn').click()]);
  await audioSite.locator('.trial-audio-player').last().waitFor();
  assert.equal(await audioSite.locator('.trial-audio-player').last().getAttribute('src'),source);
  await audioSite.close();
  assert.deepEqual(errors,[]);
  console.log('SITE_CYCLE_PASS mobile='+(width===390)+' next_gabriel=true planned_date=true menu_home=true menu_celebrations=true admin_return=true historic_mp3_in_page=true dated_week=true multi_preparation_dates=true persisted=true');
  await ctx.close();
 }
}finally{await browser.close()}
