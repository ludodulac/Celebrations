// Deterministic module composition for the existing nonce-only inline editor.
// No eval, external asset route, or runtime filesystem reads in the Worker.
import {readFileSync,writeFileSync} from 'node:fs';
const paths=["app/admin/admin-dialog.mjs","app/domain/member-access.mjs","app/domain/editor-localization.mjs","app/domain/celebration-spaces.mjs","app/admin/member-access-admin-model.mjs","app/admin/member-access-admin-ui.mjs","app/admin/member-directory-admin-integration.mjs","app/admin/editor-spaces-draft.mjs","app/admin/editor-member-spaces-integration.mjs","app/admin/real-editor-member-spaces.mjs"];
function build(paths,sources,css){
 const ids=new Map(paths.map((p,i)=>[p,"m"+i]));
 function resolve(p,rel){const parts=p.split("/").slice(0,-1);for(const s of rel.split("/")){if(s==="..")parts.pop();else if(s!==".")parts.push(s)}return parts.join("/")}
 const out=paths.map((p,i)=>{
  let s=sources[i],names=[];
  s=s.replace(/^import\s*\{([\s\S]*?)\}\s*from\s*['"]([^'"]+)['"];\s*/gm,(_,names,rel)=>{
   const id=ids.get(resolve(p,rel));if(!id)throw Error("Unknown dependency "+p+" "+rel);return "const {"+names+"}="+id+";\n";
  });
  s=s.replace(/^export\s+(function|const|let|class)\s+(\w+)/gm,(_,kind,name)=>{names.push(name);return kind+" "+name});
  s=s.replace(/^export\s*\{([^}]+)\};\s*/gm,(_,list)=>{names.push(...list.split(",").map(s=>s.trim()));return ""});
  if(/^\s*(import|export)\s/m.test(s))throw Error("Unsupported syntax "+p);
  return "const "+ids.get(p)+"=(()=>{\n"+s+"\nreturn {"+[...new Set(names)].join(",")+"};\n})();";
 }).join("\n");
 const code="const M012B=(()=>{\n"+out+"\nreturn {dialog:m0.adminDialog,mount:"+ids.get(paths.at(-1))+".mountRealEditorMemberSpaces,css:"+JSON.stringify(css)+"};\n})();";
 if(/<\/script/i.test(code))throw Error("Unsafe inline script end");
 return "// Generated by scripts/build-m012b-member-spaces-inline.mjs; DO NOT EDIT.\nexport const MEMBER_SPACES_INLINE="+JSON.stringify(code)+";\n";
}
const root=new URL('../migration/cloudflare/',import.meta.url);
const sources=paths.map(p=>readFileSync(new URL(p,root),'utf8'));
const css=readFileSync(new URL('app/admin/editor-member-spaces.css',root),'utf8')+"\n.member-session-box{padding:1rem;margin:0 0 1rem;border:1px solid #ddd;border-radius:.5rem}\n.member-session-box form{display:flex;align-items:end;gap:.5rem;flex-wrap:wrap}\n.member-session-box input{max-width:100%;min-height:44px}\n.member-session-box [hidden]{display:none!important}\n";
const output=build(paths,sources,css);
const target=new URL('app/admin/real-editor-member-spaces-inline.mjs',root);
if(process.argv.includes('--check')){
 if(readFileSync(target,'utf8')!==output)throw Error('M012B inline source out of date');
}else writeFileSync(target,output);
